import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const forbiddenSnippetsByFile: Record<string, string[]> = {
  "components/hooks/use-chat-conversations.ts": [
    '"(tool result)"',
    '"Branched Chat"',
  ],
  "lib/stores/pi-event-router.ts": [
    '"(tool result)"',
  ],
};

describe("chat persistence i18n static coverage", () => {
  it("keeps known hardcoded persisted chat fallback strings out of source", () => {
    const remaining = Object.entries(forbiddenSnippetsByFile).flatMap(
      ([file, snippets]) => {
        const source = readFileSync(join(process.cwd(), file), "utf8");
        return snippets
          .filter((snippet) => source.includes(snippet))
          .map((snippet) => `${file}: ${snippet}`);
      },
    );

    expect(remaining).toEqual([]);
  });
});
