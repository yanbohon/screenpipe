describe("settings i18n static coverage", () => {
  it("keeps known hardcoded settings UI strings out of source", () => {
    const remaining = Object.entries(forbiddenSnippetsByFile).flatMap(([file, snippets]) => {
      const source = readFileSync(join(process.cwd(), file), "utf8");
      return snippets
        .filter((snippet) => source.includes(snippet))
        .map((snippet) => `${file}: ${snippet}`);
    });

    expect(remaining).toEqual([]);
  });
});
